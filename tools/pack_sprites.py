#!/usr/bin/env python3
"""Pack the 8x8 sprites the game uses into assets/sprites.bin + src/sprites.rs.

sprites.bin layout:  [n: u8] [n x RGB565 LE palette]  [count x 64 bytes of palette indices]
Index 0 is transparent, so palette entry i lives at index i+1. Run: python3 tools/pack_sprites.py
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "src")
# (const name, sheet, tile x, tile y[, width, height in tiles]). Multi-tile sprites are stored as
# consecutive 8x8 blocks in row-major order; the constant is the first block.
SPRITES = [
    ("GRASS0", "TinyFarm_Tiles.png", 0, 1),
    ("GRASS1", "TinyFarm_Tiles.png", 0, 0),
    ("GRASS2", "TinyFarm_Tiles.png", 2, 1),
    ("GRASS3", "TinyFarm_Tiles.png", 3, 1),
    ("GRASS4", "TinyFarm_Tiles.png", 4, 1),
    ("ROCK0", "TinyFarm_MapDecorations.png", 5, 0),
    ("ROCK1", "TinyFarm_MapDecorations.png", 6, 0),
    ("WALL", "TinyFarm_Structures.png", 2, 3),
    ("DOOR", "TinyFarm_Structures.png", 3, 3),
    ("WOOD", "TinyFarm_Structures.png", 0, 10),
    ("PINE", "TinyFarm_MapDecorations.png", 6, 2, 2, 2),
    ("OAK", "TinyFarm_MapDecorations.png", 4, 4, 2, 2),
    ("CATAPULT", "catapult.png", 0, 0, 1, 2),  # hand-drawn, tools/draw_catapult.py
    ("CATAPULT_FIRED", "catapult.png", 1, 0, 1, 2),
    ("BALLISTA", "ballista.png", 0, 0, 1, 2),  # hand-drawn, tools/draw_ballista.py
    ("BALLISTA_FIRED", "ballista.png", 1, 0, 1, 2),
    ("BED", "bed.png", 0, 0),
    ("FLOOR", "floor.png", 0, 0),  # hand-drawn, tools/draw_floor.py  # hand-drawn, tools/draw_bed.py
    ("PLAYER", "characters_8x8.png", 0, 0),
    ("ZOMBIE0", "characters_8x8.png", 13, 4),
    ("ZOMBIE1", "characters_8x8.png", 14, 4),
]

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

blocks = []  # (name or None, sheet, tx, ty)
for name, sheet, tx, ty, *size in SPRITES:
    w, h = size or (1, 1)
    for j in range(h):
        for i in range(w):
            blocks.append((name if i == j == 0 else None, sheet, tx + i, ty + j))

pal, data, sheets = [], bytearray(), {}
for name, sheet, tx, ty in blocks:
    im = sheets.setdefault(sheet, Image.open(os.path.join(SRC, sheet)).convert("RGBA"))
    for y in range(8):
        for x in range(8):
            r, g, b, a = im.getpixel((tx * 8 + x, ty * 8 + y))
            if a < 128:
                data.append(0)
                continue
            c = rgb565(r, g, b)
            if c not in pal:
                pal.append(c)
            data.append(pal.index(c) + 1)
assert len(pal) <= 255, "palette overflow"

with open(os.path.join(ROOT, "assets", "sprites.bin"), "wb") as f:
    f.write(bytes([len(pal)]))
    for c in pal:
        f.write(c.to_bytes(2, "little"))
    f.write(data)
with open(os.path.join(ROOT, "src", "sprites.rs"), "w") as f:
    f.write("// Generated by tools/pack_sprites.py; do not edit.\n")
    for i, (name, *_ ) in enumerate(blocks):
        if name:
            f.write(f"pub const {name}: usize = {i};\n")
print(f"{len(blocks)} blocks, {len(pal)} colours, {1 + 2 * len(pal) + len(data)} bytes")
