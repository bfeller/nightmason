#!/usr/bin/env python3
"""Pack tools/music_designs.json (saved by the music designer) into src/music.rs.

    python3 tools/pack_music.py        (or: make music)

Every song becomes a `pub const <NAME>: Song` (e.g. "Night Theme" -> NIGHT_THEME) with the
instruments it uses. Tracks play as the designer plays them: muted tracks, and unsoloed tracks
when any track is soloed, are left out. Notes past the pattern's length are dropped.
"""
import json
import os
import re

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
SRC = os.path.join(TOOLS, "music_designs.json")
OUT = os.path.join(ROOT, "src", "music.rs")

# audio.rs VOICE, for leaving defaults out.
DEFAULT = {"wave": "Square", "freq": 440.0, "slide": 0.0, "jump": [0.0, 1.0], "duty": 0.5,
           "vib": [0.0, 0.0], "delay": 0.0, "attack": 0.0, "hold": 0.0, "decay": 0.1, "lp": 0.0,
           "lp_slide": 0.0, "hp": 0.0, "vol": 0.5}


def ident(name):
    s = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
    return s if s and not s[0].isdigit() else "M_" + s


def num(x):
    x = float(x)
    s = repr(round(x, 6))
    return s if ("." in s or "e" in s) else s + ".0"


def voice(v):
    parts = []
    for k, d in DEFAULT.items():
        x = v.get(k, d)
        if k == "duty" and v.get("wave", "Square") != "Square":
            continue
        if isinstance(d, list):
            if [float(a) for a in x] == d or (k == "jump" and float(x[1]) == 1.0) or (k == "vib" and float(x[1]) == 0.0):
                continue
            parts.append(f"{k}: ({num(x[0])}, {num(x[1])})")
        elif k == "wave":
            if x != d:
                parts.append(f"wave: Wave::{x}")
        elif float(x) != d:
            parts.append(f"{k}: {num(x)}")
    body = ", ".join(parts + ["..VOICE"])
    return (f"    InstVoice {{ v: Voice {{ {body} }}, fixed: {str(bool(v.get('fixed'))).lower()}, "
            f"gate: {str(bool(v.get('gate', True))).lower()} }},")


def main():
    data = json.load(open(SRC))
    insts = {i["name"]: i for i in data["instruments"]}
    out = [
        "//! Music, generated by tools/pack_music.py from tools/music_designs.json (the music designer).",
        "//! Don't hand-edit: change the song in the designer, save, and run `make music`.",
        "#![allow(dead_code)]",
        "use crate::audio::{InstVoice, Note, Song, Track, Voice, Wave, VOICE};",
        "",
    ]
    used = {}
    songs = []
    for s in data["songs"]:
        steps = int(s["steps"])
        solo = any(t.get("solo") for t in s["tracks"])
        keep = [i for i, t in enumerate(s["tracks"])
                if not t.get("mute") and (t.get("solo") or not solo) and t["inst"] in insts]
        tracks = []
        for i in keep:
            t = s["tracks"][i]
            used[t["inst"]] = "INST_" + ident(t["inst"])
            tracks.append(f"        Track {{ inst: {used[t['inst']]}, vol: {num(t['vol'])} }},")
        pats = []
        for p in s["patterns"]:
            lists = []
            for i in keep:
                notes = sorted((n for n in (p["notes"][i] if i < len(p["notes"]) else []) if 0 <= n["s"] < steps),
                               key=lambda n: (n["s"], n["n"]))
                lists.append("&[" + ", ".join(
                    f"Note {{ step: {n['s']}, key: {max(0, min(127, n['n']))}, len: {max(1, min(255, n['l']))}, "
                    f"vel: {max(1, min(255, round(n['v'] * 255)))} }}" for n in notes) + "]")
            pats.append(f"        // {p['name']}\n        &[\n" + "".join(f"            {l},\n" for l in lists) + "        ],")
        order = ", ".join(str(o) for o in s["order"] if 0 <= o < len(s["patterns"]))
        songs.append(
            f"/// \"{s['name']}\"\npub const {ident(s['name'])}: Song = Song {{\n"
            f"    bpm: {num(s['bpm'])},\n    steps: {steps},\n    volume: {num(s['volume'])},\n"
            f"    tracks: &[\n" + "\n".join(tracks) + "\n    ],\n"
            f"    patterns: &[\n" + "\n".join(pats) + "\n    ],\n"
            f"    order: &[{order}],\n}};\n")
    for name, const in used.items():
        out.append(f"/// \"{name}\"")
        out.append(f"const {const}: &[InstVoice] = &[")
        out += [voice(v) for v in insts[name]["voices"]]
        out.append("];")
        out.append("")
    out += songs
    with open(OUT, "w") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(songs)} song(s), {len(used)} instrument(s)")


if __name__ == "__main__":
    main()
